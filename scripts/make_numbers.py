lines = ["% Auto-generated by scripts/make_numbers.py -- do not edit by hand."]
f3 = lambda x: f"{x:.3f}"  # noqa: E731
f1 = lambda x: f"{x:.1f}"  # noqa: E731


def m(name, val):
    lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")


def load(ds):
    p = os.path.join(ROOT, ds, "summary.json")
    return json.load(open(p)) if os.path.exists(p) else None


def plural(unit, xs):
    xs = [str(x) for x in xs]
    if len(xs) == 1:
        return f"{unit}~{xs[0]}"
    return f"{unit}s~" + ", ".join(xs[:-1]) + f" and~{xs[-1]}"


def join_and(parts):
    if len(parts) <= 1:
        return "".join(parts)
    return ", ".join(parts[:-1]) + " and " + parts[-1]


def holm(pvals):
    p = np.asarray(pvals, float); n = len(p)
    order = np.argsort(p); adj = np.empty(n); run = 0.0
    for k, i in enumerate(order):
        run = max(run, min(1.0, (n - k) * p[i])); adj[i] = run
    return adj.tolist()


def rec_mean(src, mode, H, metric="NDCG@10"):
    return float(np.mean([src[str(h)][mode][metric][0] for h in range(H)]))


def rec_macros(S, H, suffix):
    rk, rb = S.get("opal_rank"), S.get("rec_baselines", {})
    if not rk or not rb:
        return
    best = {}
    for mode in ("all", "new"):
        cand = {n: rec_mean(v, mode, H) for n, v in rb.items() if all(str(h) in v and mode in v[str(h)] for h in range(H))}
        bname = max(cand, key=cand.get)
        o = rec_mean(rk, mode, H)
        best[mode] = (bname, cand[bname], o)
        m(f"ndcgOpal{mode.capitalize()}{suffix}", f3(o))
        m(f"ndcgBest{mode.capitalize()}{suffix}", f3(cand[bname]))
        m(f"bestRec{mode.capitalize()}{suffix}", bname)
        m(f"ndcgGain{mode.capitalize()}{suffix}", f1(100 * (o / cand[bname] - 1)))
    # paired Wilcoxon tests of per-learner NDCG@10 against the strongest recommender, Holm-adjusted over horizons
    unit = "week" if suffix == "" else "day"
    hnum = {"": [2, 4, 6, 8, 12], "Mooc": [1, 3, 5, 7]}[suffix]
    wil = S.get("wilcoxon", {})
    for mode in ("all", "new"):
        b = best[mode][0]
        if b not in wil:
            continue
        hs = [str(h) for h in range(H) if str(h) in wil[b] and mode in wil[b][str(h)]]
        ps = holm([wil[b][h][mode]["p"] for h in hs])
        better = [hnum[int(h)] for h, p in zip(hs, ps) if p < 0.05 and wil[b][h][mode]["opal"] > wil[b][h][mode]["base"]]
        worse = [hnum[int(h)] for h, p in zip(hs, ps) if p < 0.05 and wil[b][h][mode]["opal"] < wil[b][h][mode]["base"]]
        same = [hnum[int(h)] for h, p in zip(hs, ps) if p >= 0.05]
        parts = []
        if better:
            parts.append(f"significantly higher at {plural(unit, better)}")
        if worse:
            parts.append(f"significantly lower at {plural(unit, worse)}")
        if same:
            parts.append(f"not significantly different at {plural(unit, same)}")
        m(f"wil{mode.capitalize()}Sentence{suffix}", join_and(parts))
    for mode in ("all", "new"):
        b = best[mode][0]
        src = rb[b]
        m(f"recallOpal{mode.capitalize()}{suffix}", f3(rec_mean(rk, mode, H, "Recall@10")))
        m(f"recallBest{mode.capitalize()}{suffix}", f3(rec_mean(src, mode, H, "Recall@10")))
        m(f"ndcgDiff{mode.capitalize()}{suffix}", f"{100 * (rec_mean(rk, mode, H) - rec_mean(src, mode, H)):.1f}")
    hr = [rec_mean(rk, "all", H, "HR@10")] + [rec_mean(v, "all", H, "HR@10") for n, v in rb.items()
                                               if n in ("SASRec", "GRU4Rec", "RecentPop", "Repeat", "Pop")]
    m(f"hrAllMin{suffix}", f"{np.floor(min(hr) * 100) / 100:.2f}")
    RS = {"Pop": "Pop", "RecentPop": "RecentPop", "Repeat": "Repeat", "ItemKNN": "ItemKnn", "BPR-MF": "BprMf",
          "LightGCN": "LightGcn", "GRU4Rec": "GruRec", "SASRec": "SasRec"}
    for n, sh in RS.items():
        if n in rb:
            for mode in ("all", "new"):
                v = rec_mean(rb[n], mode, H)
                m(f"ndcg{mode.capitalize()}{sh}{suffix}", f3(v))
    fl = S.get("flagged_rec", {})
    vals = [fl[str(h)] for h in range(H) if str(h) in fl and "OPAL" in fl[str(h)] and fl[str(h)]["OPAL"]["flagged"] is not None]
    if vals:
        m(f"ndcgFlagOpal{suffix}", f3(np.mean([v["OPAL"]["flagged"] for v in vals])))
        m(f"ndcgOthersOpal{suffix}", f3(np.mean([v["OPAL"]["others"] for v in vals])))
        for b in ("SASRec", "RecentPop"):
            bv = [v[b]["flagged"] for v in vals if b in v and v[b]["flagged"] is not None]
            if bv:
                m(f"ndcgFlag{b}{suffix}", f3(np.mean(bv)))
                m(f"ndcgOthers{b}{suffix}", f3(np.mean([v[b]["others"] for v in vals if b in v and v[b]["others"] is not None])))


