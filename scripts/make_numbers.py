def fairness_macros(S, H=5):
    fa = S.get("fairness", {})
    AT = {"gender": "Gender", "age_band": "Age", "imd_band": "Imd", "disability": "Dis"}
    for n, sh in (("opal", "Opal"), ("LightGBM", "Lgbm"), ("GRU", "Gru"), ("XGBoost", "Xgb"), ("HGB+Platt", "Hgb")):
        if n not in fa:
            continue
        for a, al in AT.items():
            g = [fa[n][str(h)]["gaps"][a] for h in range(H)]
            m(f"dTpr{sh}{al}", f3(np.mean([x["dTPR"] for x in g])))
            m(f"dFpr{sh}{al}", f3(np.mean([x["dFPR"] for x in g])))
            m(f"abroca{sh}{al}", f3(np.mean([fa[n][str(h)]["abroca"][a] for h in range(H)])))
        gr = lambda a, grp, k: np.mean([fa[n][str(h)]["gaps"][a]["groups"][grp][k] for h in range(H)])  # noqa: E731
        m(f"fprFemale{sh}", f3(gr("gender", "F", "FPR"))); m(f"fprMale{sh}", f3(gr("gender", "M", "FPR")))
        m(f"tprImdUnknown{sh}", f3(gr("imd_band", "unknown", "TPR")))
        m(f"tprImdLow{sh}", f3(gr("imd_band", "low (0-50%)", "TPR")))
        m(f"tprAgeOld{sh}", f3(gr("age_band", "35+", "TPR"))); m(f"tprAgeYoung{sh}", f3(gr("age_band", "0-35", "TPR")))
    if "opal" in fa:
        m("nImdUnknown", str(int(np.mean([fa["opal"][str(h)]["gaps"]["imd_band"]["groups"]["unknown"]["n"] for h in range(H)]))))
    ab = [np.mean([fa[n][str(h)]["abroca"]["gender"] for h in range(H)]) for n in fa]
    if ab:
        m("abrocaGenderLow", f3(min(ab))); m("abrocaGenderHigh", f3(max(ab)))


def efficiency_macros(S, ds, suffix):
    """Training/inference cost.  The controlled benchmark (scripts/benchmark_efficiency.py, idle machine, one
    thread) is used when available; otherwise the times logged by the main runs, which shared the CPU."""
    import glob
    eff = {}
    p = os.path.join(ROOT, "efficiency.json")
    if os.path.exists(p):
        eff = json.load(open(p)).get(ds, {})
    m(f"effControlled{suffix}", "yes" if eff else "no")
    diffs = [e["max_abs_logit_diff_vs_main_run"] for e in eff.values() if e.get("max_abs_logit_diff_vs_main_run") is not None]
    if diffs:
        m(f"effMaxDiff{suffix}", f"{max(diffs):.1e}" if max(diffs) > 0 else "0")
        m(f"effNReproduced{suffix}", str(len(diffs)))
    R = S["risk"]
    for n, sh in (("opal", "Opal"), ("GRU", "Gru"), ("Transformer", "Trf"), ("R-GCN", "Rgcn"), ("HGT", "Hgt"),
                  ("LightGBM", "Lgbm"), ("XGBoost", "Xgb")):
        e = eff.get(n)
        if e:
            tr, inf, par = e["train_sec"], e.get("infer_sec"), e.get("n_params")
        elif n in R:
            tr, inf, par = R[n]["train_sec"], R[n]["infer_sec"], R[n]["n_params"]
        else:
            continue
        m(f"trainMin{sh}{suffix}", f1(tr / 60))
        if inf is not None:
            m(f"inferSec{sh}{suffix}", f1(inf))
        if par:
            m(f"params{sh}{suffix}", f"{int(par):,}")
    for n, sh in (("SASRec", "SasRec"), ("GRU4Rec", "GruRec")):
        e = eff.get(n)
        if e:
            m(f"fitMin{sh}{suffix}", f1(e["train_sec"] / 60)); m(f"nFits{sh}{suffix}", str(e["fits"]))
        else:
            fs = sorted(glob.glob(os.path.join(ROOT, ds, "rec", f"{n}_seed*.json")))
            if fs:
                m(f"fitMin{sh}{suffix}", f1(np.mean([json.load(open(x))["_sec"] for x in fs]) / 60))


